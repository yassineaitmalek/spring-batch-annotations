CREATE TABLE PERSON (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  -- UNIQUE IDENTIFIER FOR EACH RECORD
  REFERENCE VARCHAR(255) NOT NULL,
  -- REFERENCE FIELD, VARIABLE-LENGTH TEXT
  NAME VARCHAR(255) NOT NULL,
  -- NAME OF THE USER
  EMAIL VARCHAR(255) NOT NULL,
  -- EMAIL ADDRESS OF THE USER
  ADDRESS TEXT,
  -- ADDRESS FIELD, LONGER TEXT FOR STORING COMPLETE ADDRESS
  PHONE VARCHAR(20),
  -- PHONE NUMBER OF THE USER
  DATE_INSERT DATETIME DEFAULT CURRENT_TIMESTAMP -- TIMESTAMP FOR WHEN THE RECORD IS INSERTED
);